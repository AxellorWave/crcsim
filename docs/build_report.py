def read(path):
    with open(path, encoding="utf-8") as source:
        return list(csv.DictReader(source, delimiter=";"))


def source_function(path, signature):
    lines = (ROOT / path).read_text(encoding="utf-8").split("\n")
    start = next(index for index, line in enumerate(lines) if line.startswith(signature))
    end = next(index for index in range(start, len(lines)) if lines[index] == "}")
    return "\n".join(lines[start:end + 1])


def simulations():
    rows = {}
    for row in read(DATA / "simulations.csv"):
        rows[(row["channel"], row["level"], row["n"], row["g"])] = row
    refined = {}
    for row in read(DATA / "refined.csv"):
        refined[(row["channel"], row["level"], row["n"], row["g"])] = row
    return rows, refined


