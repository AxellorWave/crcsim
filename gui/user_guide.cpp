QString formatLists(const QString& html)
{
    static const QRegularExpression listPattern(QStringLiteral("<(ul|ol)>(.*?)</\\1>"),
        QRegularExpression::DotMatchesEverythingOption);
    static const QRegularExpression itemPattern(
        QStringLiteral("<li>(.*?)</li>"), QRegularExpression::DotMatchesEverythingOption);
    QString result;
    qsizetype position = 0;
    QRegularExpressionMatchIterator lists = listPattern.globalMatch(html);
    while (lists.hasNext()) {
        const QRegularExpressionMatch list = lists.next();
        result += html.mid(position, list.capturedStart() - position);
        const bool numbered = list.captured(1) == QStringLiteral("ol");
        int number = 0;
        QRegularExpressionMatchIterator items = itemPattern.globalMatch(list.captured(2));
        while (items.hasNext()) {
            const QString marker = numbered ? QStringLiteral("%1)").arg(++number) : QStringLiteral("–");
            result += QStringLiteral("<p class=\"item\">%1 %2</p>").arg(marker, items.next().captured(1).trimmed());
        }
        position = list.capturedEnd();
    }
    return result + html.mid(position);
}

QString sectionAnchor(int section)
{
    return QStringLiteral("s%1").arg(section);
}

QString subsectionAnchor(int section, int subsection)
{
    return QStringLiteral("s%1-%2").arg(section).arg(subsection);
}

QString tableOfContents(const std::vector<GuideSection>& sections)
{
    QString items;
    for (std::size_t i = 0; i < sections.size(); ++i) {
        const int number = static_cast<int>(i) + 1;
        items += QStringLiteral("<p class=\"toc1\"><a href=\"#%1\">%2 %3</a></p>")
                     .arg(sectionAnchor(number))
                     .arg(number)
                     .arg(sections[i].title);
        for (std::size_t j = 0; j < sections[i].subsections.size(); ++j) {
            const int sub = static_cast<int>(j) + 1;
            items += QStringLiteral("<p class=\"toc2\"><a href=\"#%1\">%2.%3 %4</a></p>")
                         .arg(subsectionAnchor(number, sub))
                         .arg(number)
                         .arg(sub)
                         .arg(sections[i].subsections[j].title);
        }
    }
    return QStringLiteral("<p class=\"contents\">Содержание</p>") + items;
}

QString sectionHtml(const GuideSection& section, int number)
{
    QString html = QStringLiteral("<a name=\"%1\"></a><h2>%2 %3</h2>")
                       .arg(sectionAnchor(number))
                       .arg(number)
                       .arg(section.title)
        + section.body;
    for (std::size_t j = 0; j < section.subsections.size(); ++j) {
        const int sub = static_cast<int>(j) + 1;
        html += QStringLiteral("<a name=\"%1\"></a><h3>%2.%3 %4</h3>")
                    .arg(subsectionAnchor(number, sub))
                    .arg(number)
                    .arg(sub)
                    .arg(section.subsections[j].title)
            + section.subsections[j].body;
    }
    return html;
}

