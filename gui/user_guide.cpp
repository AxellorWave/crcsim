GuideSection channelsSection()
{
    return {text("Модели канала связи"), QString(),
        {{text("Двоичный симметричный канал"),
             text(R"(
<p>В двоичном симметричном канале каждый бит искажается с одной и той же вероятностью p независимо от остальных
бит. Вероятность того, что блок из n бит будет принят без искажений, вычисляют по формуле</p>
)") + formula("<i>P</i><sub>в</sub> = (1 − <i>p</i>)<sup><i>n</i></sup>", 1)},
            {text("Канал Гилберта"),
                text(R"(
<p>Канал Гилберта находится в одном из двух состояний: хорошем, в котором ошибки редки, и плохом, в котором ошибки
часты. После передачи каждого бита канал переходит из хорошего состояния в плохое с вероятностью P<sub>ХП</sub> и
из плохого в хорошее с вероятностью P<sub>ПХ</sub>. В хорошем состоянии бит искажается с вероятностью
p<sub>Х</sub>, в плохом — с вероятностью p<sub>П</sub>. Такая модель описывает пачки ошибок, возникающие при
импульсных помехах и замираниях сигнала.</p>
<p>Доли времени, которые канал проводит в плохом и хорошем состояниях, вычисляют по формуле</p>
)") + formula("<i>P</i><sub>П</sub> = <i>P</i><sub>ХП</sub> / (<i>P</i><sub>ХП</sub> + <i>P</i><sub>ПХ</sub>),"
                          "&nbsp;&nbsp;&nbsp; <i>P</i><sub>Х</sub> = 1 − <i>P</i><sub>П</sub>",
                      2)
                    + text(R"(
<p>Средняя вероятность ошибки на бит, сопоставимая с вероятностью p в ДСК, равна</p>
)") + formula("<i>p̄</i> = <i>p</i><sub>Х</sub> · <i>P</i><sub>Х</sub> + <i>p</i><sub>П</sub> · <i>P</i><sub>П</sub>", 3)
                    + text(R"(
<p>Средняя длина пачки, то есть среднее число бит подряд, передаваемых в плохом состоянии, равна</p>
)") + formula("<i>L</i><sub>пачки</sub> = 1 / <i>P</i><sub>ПХ</sub>", 4) + text(R"(
<p>При параметрах по умолчанию (P<sub>ХП</sub> = 0,001; P<sub>ПХ</sub> = 0,1; p<sub>П</sub> = 0,5;
p<sub>Х</sub> = 0) средняя вероятность ошибки p̄ ≈ 0,005, средняя длина пачки — 10 бит. Значения P<sub>П</sub>,
p̄ и 1/P<sub>ПХ</sub> выводятся под полями канала.</p>
)")}}};
}

