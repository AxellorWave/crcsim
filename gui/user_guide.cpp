QString userGuideHtml()
{
    const std::vector<GuideSection> sections = guideSections();
    QStringList parts;
    parts.append(text(R"(<a name="top"></a><h1>Руководство пользователя</h1>
<p class="subtitle">Программа исследования циклических кодов в режиме обнаружения ошибок crcsim</p>)"));
    parts.append(tableOfContents(sections));
    for (std::size_t i = 0; i < sections.size(); ++i)
        parts.append(sectionHtml(sections[i], static_cast<int>(i) + 1));
    return QStringLiteral("<html><body>") + formatLists(parts.join(QString())) + QStringLiteral("</body></html>");
}
