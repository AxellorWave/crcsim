QString text(const char* utf8)
{
    return QString::fromUtf8(utf8);
}

QString formula(const char* expression, int number)
{
    return QStringLiteral("<table class=\"formula\" width=\"100%\" cellspacing=\"0\" cellpadding=\"6\"><tr>"
                          "<td width=\"12%\"></td><td align=\"center\">%1</td>"
                          "<td width=\"12%\" align=\"right\">(%2)</td></tr></table>")
        .arg(text(expression))
        .arg(number);
}

QString caption(const char* title)
{
    return QStringLiteral("<p class=\"caption\">%1</p>").arg(text(title));
}

QString gridTable(const char* rows)
{
    return QStringLiteral("<table class=\"grid\" width=\"100%\" cellpadding=\"5\" cellspacing=\"0\">%1</table>")
        .arg(text(rows));
}

GuideSection purposeSection()
{
    return {text("Назначение программы"), text(R"(
<p>Программа crcsim предназначена для исследования циклических кодов (CRC) в режиме обнаружения ошибок. Программа
формирует случайные блоки данных, кодирует их выбранным циклическим кодом, передаёт по модели канала связи и
проверяет каждый принятый блок декодером. Исход передачи блока относится к одному из трёх классов:</p>
<ul>
<li>блок принят верно — канал не исказил ни одного бита;</li>
<li>ошибка обнаружена — биты искажены, и декодер обнаружил искажение;</li>
<li>ложный приём — биты искажены, но принятое слово оказалось другим кодовым словом, и искажение не обнаружено.</li>
</ul>
<p>По результатам моделирования оцениваются вероятности исходов, избыточность кода, среднее число попыток передачи
блока и время передачи файла. Программа позволяет сравнить коды между собой и выбрать код, удовлетворяющий
требованию к вероятности ложного приёма, — в лабораторной работе P<sub>лож</sub> ≤ 10<sup>−6</sup>.</p>
<p>Программа поставляется в двух вариантах: графическом (crcsim-gui) и консольном (crcsim). Оба варианта используют
одно и то же вычислительное ядро и дают одинаковые результаты при одинаковых параметрах и начальном значении
генератора случайных чисел.</p>
)"), {}};
}

